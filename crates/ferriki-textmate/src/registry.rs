    #[test]
    fn compiling_all_scanners_exports_rules_tokenization_did_not_reach() {
        let (lazy, lazy_grammar) = archive_registry(true);
        archive_tokens(&lazy_grammar, &["fn"]);
        let lazy_archive = lazy.export_precompiled_patterns().unwrap();
        assert!(!archive_has(&lazy_archive, r"\\.", true));

        let (eager, eager_grammar) = archive_registry(true);
        eager_grammar.compile_all_scanners().unwrap();
        let eager_archive = eager.export_precompiled_patterns().unwrap();
        assert!(archive_has(&eager_archive, r"\\.", true));
        assert!(archive_len(&eager_archive) > archive_len(&lazy_archive));
        assert!(
            !archive_has(&eager_archive, r"\\.", false),
            "keys include the prefilter mode"
        );

        // Resolved end patterns bypass the cache, so tokenizing the dynamic
        // rule adds nothing to a complete archive.
        archive_tokens(&eager_grammar, &["<DOC>body<DOC>", "<AB>x<AB>"]);
        let after = eager.export_precompiled_patterns().unwrap();
        assert_eq!(archive_len(&after), archive_len(&eager_archive));
    }

    #[test]
    fn rejects_malformed_archives_and_keeps_compiling() {
        let (mut registry, grammar) = archive_registry(true);
        assert!(registry.add_precompiled_patterns(vec![1, 2, 3]).is_err());
        let mut versioned = b"FERRONI\0".to_vec();
        versioned
            .extend_from_slice(&(crate::PRECOMPILED_PATTERNS_FORMAT_VERSION + 1).to_le_bytes());
        let error = registry.add_precompiled_patterns(versioned).unwrap_err();
        assert!(
            std::error::Error::source(&error).is_some(),
            "raw archive errors retain their engine cause"
        );
        assert_eq!(
            archive_tokens(&grammar, &["fn"])[0]
                .2
                .last()
                .map(String::as_str),
            Some("keyword.archive")
        );
    }
