/* ---------- Good company ---------- */

const self = family.find((entry) => entry.name === "ferriki");
if (self === undefined) throw new Error("Ferriki is missing from the family registry");
const relations = relationsOf(self);
const kinds = {
  "runs-on": "Ferriki runs on it",
  "pairs-with": "Often used with Ferriki",
  carries: "Runs on Ferriki",
} as const;
const engines = relations.filter((relation) => relation.kind !== "carries");
const applications = relations.filter((relation) => relation.kind === "carries");
const logos: Partial<Record<string, string>> = { ardo: ardoLogo };

export function Company() {
  return (
    <MonoWide>
      <MonoCards layout="two">
        {engines.map(({ kind, tool }) => (
          <MonoCard key={tool.name} title={displayName(tool)} api={kinds[kind]}>
            <p className="fk-card-text">
              {tool.what}. {tool.does}
            </p>
            <MonoVerdict>
              <a href={toolHref(tool)}>{toolHref(tool).replace(/^https:\/\//, "")}</a>
            </MonoVerdict>
          </MonoCard>
        ))}
      </MonoCards>
      <div className="fk-apps">
        {applications.map(({ tool }) => {
          const logo = logos[tool.name];
          if (logo === undefined) throw new Error(`Add the ${tool.name} logo to the homepage`);
          return (
            <div className="fk-app" key={tool.name}>
              <img src={logo} alt={`${displayName(tool)} logo`} />
              <div>
                <h3>
                  <a href={toolHref(tool)}>{displayName(tool)}</a>
                </h3>
                <p>
                  {tool.what}. {tool.does}
                </p>
                <span className="fk-runs">{kinds.carries}</span>
              </div>
            </div>
          );
        })}
      </div>
    </MonoWide>
  );
}
