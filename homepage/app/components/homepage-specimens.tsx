/* ---------- Themes as a stylesheet ---------- */

const themeOptions = [
  { value: "light", label: "GitHub Light Default" },
  { value: "dark", label: "GitHub Dark Default" },
  { value: "monokai", label: "Monokai" },
];
const stringOptions = [
  { value: "theme", label: "Theme color" },
  { value: "page", label: "Plain, by your CSS" },
];

export function ThemeSwitch() {
  const id = useId().replaceAll(":", "");
  const [theme, setTheme] = useState("light");
  const [strings, setStrings] = useState("theme");
  const { themes } = samples;
  return (
    <figure className="mono-wide fk-themes fk-gap">
      <div className="fk-controls">
        <MonoSegmented label="Theme" value={theme} options={themeOptions} onChange={setTheme} />
        <MonoSegmented
          label="Strings"
          value={strings}
          options={stringOptions}
          onChange={setStrings}
        />
      </div>
      {/* The generated rules come with the sample; the one override is the page's own. */}
      <style>{`${themes.css}
[data-fk-sample="${id}"][data-fk-strings="page"] .tok-string { color: inherit; }`}</style>
      <div
        className="fk-theme-sample"
        data-fk-sample={id}
        data-ferriki-theme={theme}
        data-fk-strings={strings}
      >
        <Rendered html={themes.html} />
      </div>
      <figcaption className="mono-caption">
        Real output of @ferriki/core {core}: one highlighting run, three themes as CSS rules.
        Switching changes a single attribute; the token elements stay where they are.
      </figcaption>
    </figure>
  );
}

