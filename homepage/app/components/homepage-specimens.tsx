/**
 * The ground a block of inline-styled output names for itself: a color, or
 * the fallback of the variable Ferriki lets a page override. Ardo clears the
 * background of every `.shiki` block on its pages, so the frame around the
 * block carries it instead, and the theme's colors keep their contrast.
 */
function groundOf(html: string): string | undefined {
  return /^<pre[^>]*style="background-color:(?:var\(--ferriki-background-color, )?(#[\da-f]+)/i.exec(
    html,
  )?.[1];
}

/** Fixed, generated HTML from scripts/render-homepage-samples.mjs; never visitor input. */
function Rendered({ html, className }: { html: string; className?: string }) {
  const ground = groundOf(html);
  const classes = ["fk-highlighted", ground === undefined ? "" : "fk-grounded", className ?? ""];
  return (
    <div
      className={classes.filter(Boolean).join(" ")}
      style={ground === undefined ? undefined : { background: ground }}
      // Generated by scripts/render-homepage-samples.mjs; fixed at build time.
      // oxlint-disable-next-line react/no-danger -- real Ferriki output, never visitor input.
      dangerouslySetInnerHTML={{ __html: html }}
    />
  );
}

/* ---------- Prepared packages ---------- */

type Diagnostics = (typeof samples.prepared)["prepared"];
const fields: Array<[keyof Diagnostics, string]> = [
  ["mode", "regex mode"],
  ["preparedArchives", "prepared archives opened"],
  ["loadedPreparedGroups", "prepared groups restored"],
  ["staticScanners", "scanners in use"],
  ["invalidPreparedGroups", "groups rejected"],
  ["assemblyFallbacks", "fallbacks to source"],
];

function DiagnosticsList({ value }: { value: Diagnostics }) {
  return (
    <ul className="fk-out-list">
      {fields.map(([key, label]) => (
        <li key={key}>
          <span>{label}</span>
          <span>{String(value[key])}</span>
        </li>
      ))}
    </ul>
  );
}

